// Generates schema.sql and seed.sql from src/lib/collections.ts and src/lib/seed-data.ts.
// Run with: npm run db:generate   (Node 22.18+ runs TypeScript directly)
import { writeFileSync } from "node:fs";
import { collections, collectionKeys, isJsonField, sqlType } from "../src/lib/collections.ts";
import { seed } from "../src/lib/seed-data.ts";

const header = (title: string) =>
  `-- ${title}\n-- Generated by \`npm run db:generate\`. Edit src/lib/collections.ts or src/lib/seed-data.ts, not this file.\n`;

function quote(value: unknown): string {
  if (value == null) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  if (typeof value === "boolean") return value ? "1" : "0";
  return `'${String(value).replace(/'/g, "''")}'`;
}

// ───────── schema.sql ─────────
let schema = header("The Wifii / Culture Lives Here: Cloudflare D1 schema");
schema += "-- Apply with: npx wrangler d1 execute thewifii-db --remote --file=./schema.sql\n\n";

for (const key of collectionKeys) {
  const c = collections[key];
  schema += `-- ${c.label}: ${c.description}\n`;
  schema += `CREATE TABLE IF NOT EXISTS ${c.table} (\n  id TEXT PRIMARY KEY,\n`;
  for (const f of c.fields) {
    const notNull = f.required ? " NOT NULL" : "";
    const note = isJsonField(f) ? " -- JSON array" : f.type === "flame" ? " -- 0.0 to 5.0" : f.type === "boolean" ? " -- 0 or 1" : "";
    schema += `  ${f.name} ${sqlType(f)}${notNull},${note}\n`;
  }
  schema += "  created_at TEXT NOT NULL,\n  updated_at TEXT NOT NULL\n);\n";
  if (c.fields.some((f) => f.name === "status")) schema += `CREATE INDEX IF NOT EXISTS idx_${c.table}_status ON ${c.table} (status);\n`;
  if (c.fields.some((f) => f.name === "slug")) schema += `CREATE INDEX IF NOT EXISTS idx_${c.table}_slug ON ${c.table} (slug);\n`;
  schema += "\n";
}

schema += `-- Dashboard accounts. The admin signs in with the ADMIN_PASSWORD secret and is not stored here.
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  role TEXT NOT NULL DEFAULT 'contributor', -- 'admin' or 'contributor'
  password_hash TEXT NOT NULL,              -- PBKDF2-SHA256, never plain text
  created_at TEXT NOT NULL
);

-- Brand inquiries, contact messages, beat inquiries and newsletter signups.
CREATE TABLE IF NOT EXISTS submissions (
  id TEXT PRIMARY KEY,
  kind TEXT NOT NULL,
  name TEXT,
  email TEXT,
  payload TEXT NOT NULL, -- JSON object
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_submissions_created ON submissions (created_at);

-- Key/value settings (for example the Spotify refresh token saved by /api/spotify/callback).
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
`;
writeFileSync("schema.sql", schema);

// ───────── seed.sql ─────────
const now = "2026-11-16T00:00:00.000Z";
let sql = header("The Wifii / Culture Lives Here: sample content");
sql += "-- Apply after schema.sql: npx wrangler d1 execute thewifii-db --remote --file=./seed.sql\n";
sql += "-- Safe to re-run: rows are replaced by id.\n\n";

for (const key of collectionKeys) {
  const c = collections[key];
  const rows = seed[key] as unknown as Record<string, unknown>[];
  const cols = ["id", ...c.fields.map((f) => f.name), "created_at", "updated_at"];
  sql += `-- ${c.label} (${rows.length})\n`;
  for (const row of rows) {
    const values = cols.map((col) => {
      if (col === "created_at" || col === "updated_at") return quote(now);
      const f = c.fields.find((x) => x.name === col);
      const v = row[col];
      return f && isJsonField(f) ? quote(JSON.stringify(v ?? [])) : quote(v);
    });
    sql += `INSERT OR REPLACE INTO ${c.table} (${cols.join(", ")}) VALUES (${values.join(", ")});\n`;
  }
  sql += "\n";
}
writeFileSync("seed.sql", sql);

console.log("Wrote schema.sql and seed.sql");
